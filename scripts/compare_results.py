#!/usr/bin/env python
"""Side-by-side tables (markdown) for the experiment runs.

  scripts/compare_results.py --run A=experiments/direct_sft_<ts> --run B=experiments/cpt_then_sft_<ts> ... > table.md

Reads <run>/eval_test/summary.json, <run>/loss_{test,validation}.json and
<run>/train_log.jsonl. Adds bootstrap 95% intervals over songs for the main
generation metrics and a paired bootstrap for the A-B difference.
"""

from __future__ import annotations

import argparse
import json
import random
from pathlib import Path

GEN_METRICS = [
    ("strict_valid", "strict-valid ABC"),
    ("bar_duration_ok_frac", "bars with correct duration"),
    ("lyric_alignment_valid", "no lyric-alignment error"),
    ("lyric_recall", "lyric recall (in order)"),
    ("lyric_precision", "lyric precision"),
    ("lyric_exact", "lyrics exactly as requested"),
    ("section_lyric_recall", "lyric recall inside requested section"),
    ("bar_count_match", "total bar count = request"),
    ("bar_beats_match_frac", "bar lengths = request (per bar)"),
    ("section_plan_exact", "section labels+bars = request"),
    ("section_label_seq_match", "section label sequence = request"),
    ("key_match", "K: = requested key"),
    ("tempo_match", "Q: = requested tempo"),
    ("notes_per_syllable", "notes per syllable"),
    ("melisma_note_frac", "melisma note fraction"),
    ("wordless_note_frac", "wordless note fraction"),
    ("multi_syllable_note_frac", "multi-syllable note fraction"),
    ("notes_per_bar", "notes per bar"),
    ("pitch_range", "pitch range (semitones)"),
    ("mean_abs_interval", "mean |interval|"),
    ("large_leap_frac", "leaps > 7 semitones"),
    ("mean_duration_beats", "mean note duration (beats)"),
    ("offbeat_16th_frac", "16th off-beat onsets"),
    ("melody_time_frac", "time covered by melody"),
    ("chords_per_bar", "chords per bar"),
    ("chord_valid_frac", "valid chord symbols"),
    ("chord_time_coverage", "time covered by a chord"),
    ("notes_under_chord_frac", "notes with a chord"),
    ("chord_tone_frac", "chord-tone agreement (dur.-weighted)"),
    ("distinct_bar_frac", "distinct non-empty bars"),
    ("max_identical_consecutive_bars", "max identical consecutive bars"),
    ("gzip_ratio", "gzip ratio of note stream"),
]


def load_rows(eval_dir: Path):
    rows = {}
    for p in sorted((eval_dir / "generations").glob("*_s0.json")):
        r = json.loads(p.read_text(encoding="utf-8"))
        rows[r["song_id"]] = r
    return rows


def metric_value(row, key):
    if key == "strict_valid":
        return float(row["strict_ok"])
    m = row.get("metrics")
    if m is None:  # unparseable output: counts as failure for rates, excluded otherwise
        return 0.0 if key in ("lyric_recall", "lyric_precision", "lyric_exact", "section_lyric_recall",
                              "bar_count_match", "bar_beats_match_frac", "section_plan_exact",
                              "lyric_alignment_valid") else None
    v = m.get(key)
    return None if v is None or v != v else float(v)


def boot_ci(vals, n=2000, seed=0):
    rng = random.Random(seed)
    means = sorted(sum(rng.choice(vals) for _ in vals) / len(vals) for _ in range(n))
    return means[int(0.025 * n)], means[int(0.975 * n)]


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--run", action="append", required=True, help="name=experiment_dir")
    ap.add_argument("--baseline", default=None, help="name of run for paired differences (default: first)")
    args = ap.parse_args()
    runs = dict(r.split("=", 1) for r in args.run)
    names = list(runs)
    base = args.baseline or names[0]
    rows = {n: load_rows(Path(p) / "eval_test") for n, p in runs.items()}
    summaries = {n: json.loads((Path(p) / "eval_test" / "summary.json").read_text()) for n, p in runs.items()
                 if (Path(p) / "eval_test" / "summary.json").exists()}
    common = sorted(set.intersection(*(set(r) for r in rows.values())))
    print(f"Test songs generated by every run: **{len(common)}**\n")

    # losses
    print("| run | test loss (nats/token) | test ppl | validation loss | final train-log eval loss |")
    print("|---|---|---|---|---|")
    for n, p in runs.items():
        cells = []
        for split in ("test", "validation"):
            f = Path(p) / f"loss_{split}.json"
            if f.exists():
                d = json.loads(f.read_text())
                cells.append((f"{d['loss']:.4f}", f"{d['ppl']:.3f}"))
            else:
                cells.append(("–", "–"))
        last = "–"
        log = Path(p) / "train_log.jsonl"
        if log.exists():
            ev = [json.loads(l) for l in log.read_text().splitlines() if '"eval_loss"' in l]
            if ev:
                last = f"{ev[-1]['eval_loss']:.4f} (step {ev[-1]['step']})"
        print(f"| {n} | {cells[0][0]} | {cells[0][1]} | {cells[1][0]} | {last} |")
    print()

    # validity
    print("| run | parse success | strict valid | MIDI success | stopped with EOS |")
    print("|---|---|---|---|---|")
    for n in names:
        rs = [rows[n][s] for s in common]
        print(f"| {n} | {sum(r['parse_ok'] for r in rs)}/{len(rs)} | {sum(r['strict_ok'] for r in rs)}/{len(rs)} | "
              f"{sum(bool(r.get('midi_ok')) for r in rs)}/{len(rs)} | {sum(r['hit_eos'] for r in rs)}/{len(rs)} |")
    print()

    # generation metrics with CIs
    ref = summaries.get(base, {}).get("reference", {})
    header = "| metric | reference | " + " | ".join(f"{n} mean [95% CI]" for n in names) + \
             "".join(f" | {n} − {base} [95% CI]" for n in names if n != base) + " |"
    print(header)
    print("|" + "---|" * (2 + len(names) + len(names) - 1))
    for key, label in GEN_METRICS:
        cells = [f"{ref[key]['mean']:.3f}" if key in ref else "–"]
        per = {}
        for n in names:
            vals = [metric_value(rows[n][s], key) for s in common]
            per[n] = vals
            v = [x for x in vals if x is not None]
            if v:
                lo, hi = boot_ci(v)
                cells.append(f"{sum(v) / len(v):.3f} [{lo:.3f}, {hi:.3f}]")
            else:
                cells.append("–")
        for n in names:
            if n == base:
                continue
            pairs = [(a, b) for a, b in zip(per[n], per[base]) if a is not None and b is not None]
            if pairs:
                d = [a - b for a, b in pairs]
                lo, hi = boot_ci(d)
                star = " *" if lo > 0 or hi < 0 else ""
                cells.append(f"{sum(d) / len(d):+.3f} [{lo:+.3f}, {hi:+.3f}]{star}")
            else:
                cells.append("–")
        print(f"| {label} | " + " | ".join(cells) + " |")
    print("\n`*` = paired bootstrap interval excludes 0.\n")

    # distributions
    print("| run | JS pitch class | JS scale degree | JS interval | JS onset position | JS duration |")
    print("|---|---|---|---|---|---|")
    for n in names:
        js = summaries.get(n, {}).get("distribution_js_vs_reference", {})
        print(f"| {n} | " + " | ".join(f"{js.get(k, float('nan')):.4f}" for k in
                                       ("js_pc", "js_pc_rel", "js_interval", "js_onset", "js_duration")) + " |")
    print()

    # probes
    print("| run | lyric swap: melody distance | reseed: melody distance (noise floor) | tempo ×1.25 followed | "
          "notes/bar ratio under tempo change | key +5 followed | in-new-scale (generated / old output) |")
    print("|---|---|---|---|---|---|---|")
    for n in names:
        pr = summaries.get(n, {}).get("probes")
        if not pr:
            print(f"| {n} | – | – | – | – | – | – |")
            continue

        def g(sec, k):
            return pr.get(sec, {}).get(k, {}).get("mean", float("nan"))

        print(f"| {n} | {g('lyric_swap', 'melody_distance'):.3f} | {g('reseed_noise_floor', 'melody_distance'):.3f} | "
              f"{g('tempo_change', 'tempo_followed'):.2f} | {g('tempo_change', 'notes_per_bar_ratio'):.2f} | "
              f"{g('key_change', 'key_followed'):.2f} | {g('key_change', 'in_new_scale'):.2f} / "
              f"{g('key_change', 'baseline_in_new_scale'):.2f} |")
    print()

    # loss by category
    cats = ["pitch", "duration", "lyric_text", "lyric_marker", "lyric_bar", "chord", "bar", "rest", "tie", "structure"]
    print("| run | " + " | ".join(cats) + " |")
    print("|---|" + "---|" * len(cats))
    for n, p in runs.items():
        f = Path(p) / "loss_test.json"
        if not f.exists():
            continue
        bc = json.loads(f.read_text())["by_category"]
        print(f"| {n} | " + " | ".join(f"{bc[c]['loss']:.3f}" if c in bc else "–" for c in cats) + " |")


if __name__ == "__main__":
    main()
